import { render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { MemoryRouter, Route, Routes } from 'react-router-dom';
import Report from '../../src/pages/Report';
import BlockedPeople from '../../src/pages/BlockedPeople';
import { SafetyActions } from '../../src/components/discovery/SafetyActions';
const mocks = vi.hoisted(() => ({ report: vi.fn(), block: vi.fn(), unblock: vi.fn(), blocked: vi.fn(), refresh: vi.fn() }));
vi.mock('../../src/contexts/UserContext', () => ({ useUser: () => ({ user: { id: 1 } }) }));
vi.mock('../../src/contexts/DiaryContext', () => ({ useDiary: () => ({ refresh: mocks.refresh }) }));
vi.mock('../../src/services/safetyService', () => ({ reportReasons: ['Harassment', 'Spam'], safetyService: mocks }));
beforeEach(() => { vi.resetAllMocks(); mocks.blocked.mockResolvedValue({ people: [], nextOffset: null }); });
const report = () => render(<MemoryRouter initialEntries={['/report/response/11?personId=2&username=friend']}><Routes><Route path="/report/:kind/:id" element={<Report />} /></Routes></MemoryRouter>);
it('keeps report details on failure, then retries only the block after report success', async () => {
  mocks.report.mockRejectedValueOnce(new Error('offline')).mockResolvedValueOnce(undefined);
  mocks.block.mockRejectedValueOnce(new Error('offline')).mockResolvedValueOnce(undefined);
  report();
  await userEvent.type(screen.getByRole('textbox'), 'Please review this.');
  await userEvent.click(screen.getByRole('checkbox'));
  await userEvent.click(screen.getByRole('button', { name: 'Send report' }));
  expect(await screen.findByRole('alert')).toHaveTextContent('Your report could not be sent');
  expect(screen.getByRole('textbox')).toHaveValue('Please review this.');
  expect(mocks.block).not.toHaveBeenCalled();
  await userEvent.click(screen.getByRole('button', { name: 'Send report' }));
  expect(await screen.findByRole('heading', { name: 'Report received' })).toBeInTheDocument();
  expect(screen.queryByRole('button', { name: 'Send report' })).not.toBeInTheDocument();
  await userEvent.click(await screen.findByRole('button', { name: 'Retry block' }));
  expect(await screen.findByText('friend is blocked. Follows between you have been removed.')).toBeInTheDocument();
  expect(mocks.report).toHaveBeenCalledTimes(2);
  expect(mocks.report).toHaveBeenLastCalledWith({ targetKind: 'response', targetId: 11, reason: 'Harassment', details: 'Please review this.' });
  expect(mocks.block).toHaveBeenCalledTimes(2);
  expect(mocks.refresh).toHaveBeenCalledTimes(1);
});
it('leaves blocking optional and provides a report receipt', async () => {
  report();
  await userEvent.click(screen.getByRole('button', { name: 'Send report' }));
  await screen.findByRole('heading', { name: 'Report received' });
  expect(mocks.block).not.toHaveBeenCalled();
});
it('confirms a standalone block and leaves the now-restricted surface after success', async () => {
  render(<MemoryRouter><Routes><Route path="/" element={<SafetyActions kind="person" personId={2} targetId={2} username="friend" />} /><Route path="/account/blocked" element={<h1>Blocked people</h1>} /></Routes></MemoryRouter>);
  await userEvent.click(screen.getByText('Person options'));
  expect(screen.getByRole('link', { name: 'Report person' })).toHaveAttribute('href', '/report/person/2?personId=2&username=friend');
  await userEvent.click(screen.getByRole('button', { name: 'Block @friend' }));
  expect(mocks.block).not.toHaveBeenCalled();
  await userEvent.click(screen.getByRole('button', { name: 'Confirm block' }));
  expect(await screen.findByRole('heading', { name: 'Blocked people' })).toBeInTheDocument();
  expect(mocks.refresh).toHaveBeenCalledTimes(1);
});
it('pages blocks, retains failed unblocks, and separates unblock success from refresh failure', async () => {
  mocks.blocked.mockResolvedValueOnce({ people: [{ id: 2, username: 'friend' }], nextOffset: 30 }).mockResolvedValueOnce({ people: [{ id: 3, username: 'older' }], nextOffset: null }).mockRejectedValueOnce(new Error('offline'));
  mocks.unblock.mockRejectedValueOnce(new Error('offline')).mockResolvedValueOnce(undefined);
  render(<MemoryRouter><BlockedPeople /></MemoryRouter>);
  const unblock = await screen.findByRole('button', { name: 'Unblock @friend' });
  expect(mocks.blocked).toHaveBeenCalledTimes(1);
  await userEvent.click(screen.getByRole('button', { name: 'More people' }));
  await screen.findByRole('button', { name: 'Unblock @older' });
  expect(mocks.blocked).toHaveBeenLastCalledWith(30, expect.any(AbortSignal));
  await userEvent.click(unblock);
  expect(await screen.findByRole('alert')).toHaveTextContent('This person could not be unblocked');
  await userEvent.click(unblock);
  expect(await screen.findByRole('status')).toHaveTextContent('friend is unblocked');
  await waitFor(() => expect(mocks.blocked).toHaveBeenCalledTimes(3));
  expect(screen.queryByRole('button', { name: 'Unblock @friend' })).not.toBeInTheDocument();
  expect(screen.getByRole('button', { name: 'Unblock @older' })).toBeInTheDocument();
});
